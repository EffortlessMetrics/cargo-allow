#[test]
fn write_path_and_floor_comparisons_reject_traversal_and_older_toolchains() -> TestResult {
    for path in ["relative/tail.txt", "nested.dir/file.md", "a-b_c.txt"] {
        if !write_path(path) {
            return Err(format!("bounded relative path {path} refused").into());
        }
    }
    for path in [
        "/absolute",
        "../escape",
        "nested/../escape",
        "C:/drive",
        "",
        "white space",
    ] {
        if write_path(path) {
            return Err(format!("malformed write path {path:?} accepted").into());
        }
    }
    let floor = rust_floor_token("1.95").ok_or("floor token refused")?;
    let floor_patch = rust_floor_token("1.95.0").ok_or("patched floor token refused")?;
    let newer = rust_floor_token("1.96").ok_or("newer token refused")?;
    let older_toolchain = rust_floor_token("1.94.9").ok_or("older token refused")?;
    if !rust_floor_satisfied(&floor, &floor_patch) || !rust_floor_satisfied(&floor, &newer) {
        return Err("satisfied floors were refused".into());
    }
    if rust_floor_satisfied(&newer, &older_toolchain) {
        return Err("a floor above the used toolchain was accepted".into());
    }
    if rust_floor_token("selected-toolchain").is_some() || rust_floor_token("1.9999").is_some() {
        return Err("non-version or over-wide tokens parsed as versions".into());
    }
    Ok(())
}
