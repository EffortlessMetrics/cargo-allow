use super::*;
use ReleaseExperienceDocsCheckKindV1 as Kind;
use ReleaseExperienceDocsCheckOutcomeV1 as Outcome;
use ReleaseExperienceResultV1 as State;

type TestResult = Result<(), Box<dyn std::error::Error>>;

const BINARY: &str = "sha256:71bfd25a06dfa8fb14c7ee820ed9bce7f30ee84feef71a483c09274e3e7df86c";

/// Receipt-free positional accessor: no bracket indexing, no `unwrap`.
fn check_at<'a>(
    checks: &'a mut [ReleaseExperienceDocsCheckV1],
    index: usize,
    label: &'static str,
) -> &'a mut ReleaseExperienceDocsCheckV1 {
    checks
        .get_mut(index)
        .unwrap_or_else(|| std::panic::panic_any(label))
}

fn claim_check(id: &str, docs_name: &str) -> ReleaseExperienceDocsCheckV1 {
    ReleaseExperienceDocsCheckV1 {
        id: id.to_string(),
        docs_name: docs_name.to_string(),
        kind: Kind::ClaimInspection,
        command: None,
        argv: Vec::new(),
        exit_code: None,
        expected_exit_code: None,
        stdout_excerpt: String::new(),
        stderr_excerpt: String::new(),
        declared_writes: Vec::new(),
        observed_writes: Vec::new(),
        documented_claim: "the shipped doc advertises this surface".to_string(),
        observed_summary: "observed installed metadata agrees with the documented claim"
            .to_string(),
        outcome: Outcome::Matched,
    }
}

fn executed(
    id: &str,
    docs_name: &str,
    kind: Kind,
    command: &str,
    argv: &[&str],
    stdout: &str,
) -> ReleaseExperienceDocsCheckV1 {
    ReleaseExperienceDocsCheckV1 {
        kind,
        command: Some(command.to_string()),
        argv: argv.iter().map(|argument| argument.to_string()).collect(),
        exit_code: Some(0),
        expected_exit_code: Some(0),
        stdout_excerpt: stdout.to_string(),
        documented_claim: "the shipped doc advertises this command".to_string(),
        observed_summary: "executed the documented command in an owned fixture".to_string(),
        ..claim_check(id, docs_name)
    }
}

fn record(checks: Vec<ReleaseExperienceDocsCheckV1>) -> ReleaseExperienceDocsExecutionV1 {
    ReleaseExperienceDocsExecutionV1 {
        schema_id: RELEASE_EXPERIENCE_DOCS_EXECUTION_SCHEMA_ID.to_string(),
        schema_version: RELEASE_EXPERIENCE_DOCS_EXECUTION_SCHEMA_VERSION,
        binary_digest: BINARY.to_string(),
        installed_version_output: "cargo-allow 0.2.0-rc.1".to_string(),
        invocation_path: "install-root/bin/cargo-allow".to_string(),
        platform: "x86_64-pc-windows-host".to_string(),
        toolchain: "1.95.0".to_string(),
        channel_claim: "public-prerelease".to_string(),
        version_claim: "cargo-allow 0.2.0-rc.1".to_string(),
        rust_floor_claim: "1.95".to_string(),
        checks,
        limitations: Vec::new(),
        claim_boundary: "installed documentation observations only; no release authorization"
            .to_string(),
        observed_at_unix_seconds: 1_700_000_000,
        maximum_age_seconds: 600,
    }
}

/// Every docs name is covered with internally consistent declarations. These
/// rows are not the required selected-case producer or semantic output proof.
fn complete_checks() -> Vec<ReleaseExperienceDocsCheckV1> {
    let mut checks = vec![
        executed(
            "E.help.entrypoint",
            "help",
            Kind::SurfaceGeneration,
            "help",
            &["--help"],
            "Usage: cargo-allow help [COMMAND]\n  init  adopt  audit  check",
        ),
        executed(
            "E.reference.entrypoint",
            "command-registry",
            Kind::SurfaceGeneration,
            "reference",
            &["reference", "--format", "json"],
            r#"{"schema":"cargo-allow.cli-reference.v1","version":"0.2.0-rc.1","commands":[]}"#,
        ),
        executed(
            "E.man.entrypoint",
            "manpage",
            Kind::SurfaceGeneration,
            "reference",
            &["reference", "--format", "man"],
            ".TH CARGO\\-ALLOW\nGenerated by cargo-allow reference; .B cargo\\-allow check",
        ),
        executed(
            "E.completions.entrypoint",
            "completion",
            Kind::SurfaceGeneration,
            "completions",
            &["completions", "bash"],
            "cargo__allow__subcmd__completions() { ... }",
        ),
        executed(
            "docs.first-hour.journey-green",
            "getting-started",
            Kind::SnippetExecution,
            "check",
            &["check", "--mode", "no-new"],
            "**Result:** passed (enforcing)",
        ),
        claim_check("docs.channel.version-claim", "channel"),
        claim_check("docs.support.rust-floor", "support-matrix"),
        claim_check("E.package.entrypoint.readme", "readme"),
    ];
    let journey = checks
        .iter_mut()
        .find(|check| check.id == "docs.first-hour.journey-green")
        .unwrap_or_else(|| std::panic::panic_any("journey check missing"));
    journey.declared_writes = vec![
        "policy/allow.toml".to_string(),
        "target/cargo-allow/check.receipt.json".to_string(),
    ];
    journey.observed_writes = vec!["policy/allow.toml".to_string()];
    checks
}

#[test]
fn consistent_record_with_all_identities_remains_not_proven() -> TestResult {
    let evaluation = evaluate_release_experience_docs_execution_v1(&record(complete_checks()));
    if evaluation.result != State::NotProven
        || !evaluation
            .gaps
            .iter()
            .any(|gap| gap.contains("selected-case producer"))
    {
        return Err(format!("declarations became proof: {:?}", evaluation.gaps).into());
    }
    Ok(())
}

#[test]
fn prose_only_claims_cannot_prove_installed_documentation_execution() -> TestResult {
    let checks = RELEASE_EXPERIENCE_REQUIRED_DOCS
        .iter()
        .map(|name| claim_check(&format!("unexecuted-{name}"), name))
        .collect();
    let evaluation = evaluate_release_experience_docs_execution_v1(&record(checks));
    if evaluation.result == State::Complete {
        return Err("eight prose claims with no argv, exit or output proved execution".into());
    }
    Ok(())
}

#[test]
fn every_negative_control_stays_below_complete_with_a_named_reason() -> TestResult {
    let honest_disagreement = {
        let mut checks = complete_checks();
        check_at(&mut checks, 0, "help surface check present").outcome = Outcome::Mismatched;
        check_at(&mut checks, 0, "help surface check present").observed_summary =
            "the documented flag is absent from the installed surface".to_string();
        record(checks)
    };
    let cases: Vec<(&str, ReleaseExperienceDocsExecutionV1, State, &str)> = vec![
        (
            "honest red-path disagreement",
            honest_disagreement,
            State::Mismatch,
            "observed a disagreement",
        ),
        (
            "missing identity coverage",
            {
                let mut checks = complete_checks();
                checks.remove(0);
                record(checks)
            },
            State::Incomplete,
            "has no recorded check",
        ),
        (
            "empty checks",
            record(Vec::new()),
            State::Incomplete,
            "no documentation checks were recorded",
        ),
        (
            "unknown docs identity",
            record(vec![claim_check("x", "blog")]),
            State::Malformed,
            "unknown docs identity blog",
        ),
        (
            "duplicate check id",
            {
                let duplicated = complete_checks().remove(0);
                record(vec![duplicated.clone(), duplicated])
            },
            State::Malformed,
            "duplicate documentation check",
        ),
        (
            "undeclared write",
            {
                let mut checks = complete_checks();
                check_at(&mut checks, 4, "journey check present")
                    .observed_writes
                    .push("untracked/leak.txt".to_string());
                record(checks)
            },
            State::Mismatch,
            "undeclared write",
        ),
        (
            "absolute write path",
            {
                let mut checks = complete_checks();
                check_at(&mut checks, 4, "journey check present")
                    .observed_writes
                    .push("C:/abs/path".to_string());
                record(checks)
            },
            State::Malformed,
            "malformed observed write path",
        ),
        (
            "nonzero exit claimed matched",
            {
                let mut checks = complete_checks();
                check_at(&mut checks, 0, "help surface check present").exit_code = Some(2);
                record(checks)
            },
            State::Mismatch,
            "while the documented expectation is 0",
        ),
        (
            "matched without output",
            {
                let mut checks = complete_checks();
                check_at(&mut checks, 0, "help surface check present")
                    .stdout_excerpt
                    .clear();
                record(checks)
            },
            State::Incomplete,
            "matched without observed output",
        ),
        (
            "unvalidated surface output cannot prove its claim",
            {
                let mut checks = complete_checks();
                check_at(&mut checks, 0, "help surface check present").stdout_excerpt =
                    "unrelated banner".to_string();
                record(checks)
            },
            State::NotProven,
            "selected-case producer",
        ),
        (
            "snippet without argv",
            {
                let mut checks = complete_checks();
                check_at(&mut checks, 4, "journey check present")
                    .argv
                    .clear();
                record(checks)
            },
            State::Incomplete,
            "recorded no executed argv",
        ),
        (
            "executed without captured exit",
            {
                let mut checks = complete_checks();
                check_at(&mut checks, 0, "help surface check present").exit_code = None;
                record(checks)
            },
            State::Incomplete,
            "without a captured exit",
        ),
        (
            "claim inspection with exit but no argv",
            {
                let mut checks = complete_checks();
                check_at(&mut checks, 5, "channel claim check present").exit_code = Some(0);
                record(checks)
            },
            State::Malformed,
            "claims an exit without executed argv",
        ),
        (
            "not-executed check keeps the aggregate incomplete",
            {
                let mut checks = complete_checks();
                check_at(&mut checks, 7, "readme claim check present").outcome =
                    Outcome::NotExecuted;
                check_at(&mut checks, 7, "readme claim check present").observed_summary =
                    "rustdoc cannot be executed by the docs producer".to_string();
                record(checks)
            },
            State::Incomplete,
            "was not executed",
        ),
        (
            "malformed binary digest",
            ReleaseExperienceDocsExecutionV1 {
                binary_digest: "not-a-digest".to_string(),
                ..record(Vec::new())
            },
            State::Malformed,
            "binary_digest",
        ),
        (
            "empty required metadata",
            ReleaseExperienceDocsExecutionV1 {
                rust_floor_claim: String::new(),
                ..record(Vec::new())
            },
            State::Malformed,
            "rust_floor_claim",
        ),
        (
            "unparseable rust floor",
            ReleaseExperienceDocsExecutionV1 {
                rust_floor_claim: "anything".to_string(),
                ..record(complete_checks())
            },
            State::Malformed,
            "rust_floor_claim is not a comparable version",
        ),
        (
            "zero freshness window",
            ReleaseExperienceDocsExecutionV1 {
                maximum_age_seconds: 0,
                ..record(Vec::new())
            },
            State::Malformed,
            "freshness window",
        ),
        (
            "unbounded limitation",
            ReleaseExperienceDocsExecutionV1 {
                limitations: vec![" ".repeat(RELEASE_EXPERIENCE_MAX_TEXT_LEN + 1)],
                ..record(Vec::new())
            },
            State::Malformed,
            "limitations are unbounded",
        ),
        (
            "foreign schema generation",
            ReleaseExperienceDocsExecutionV1 {
                schema_id: "cargo-allow.release-experience-docs-execution.v0".to_string(),
                ..record(Vec::new())
            },
            State::Unsupported,
            "non-current docs-execution generation",
        ),
    ];
    for (label, candidate, expected, fragment) in cases {
        let evaluation = evaluate_release_experience_docs_execution_v1(&candidate);
        // Fail-closed precedence: the control must fail at least as hard as
        // expected and must name its specific reason.
        if evaluation.result > expected || evaluation.result == State::Complete {
            return Err(format!(
                "control {label} read {:?} (wanted at most {expected:?}): {:?}",
                evaluation.result, evaluation.gaps
            )
            .into());
        }
        if !evaluation.gaps.iter().any(|gap| gap.contains(fragment)) {
            return Err(format!(
                "control {label} lost its named reason: {:?}",
                evaluation.gaps
            )
            .into());
        }
    }
    Ok(())
}

#[test]
fn documented_red_paths_stay_matched_at_their_own_expected_exit() -> TestResult {
    let mut checks = complete_checks();
    checks.push(ReleaseExperienceDocsCheckV1 {
        kind: Kind::SnippetExecution,
        command: Some("check".to_string()),
        argv: vec![
            "check".to_string(),
            "--mode".to_string(),
            "no-new".to_string(),
        ],
        exit_code: Some(1),
        expected_exit_code: Some(1),
        stdout_excerpt: "Result: failed (1 new)".to_string(),
        documented_claim: "the gate fails non-zero on one new unreceipted finding".to_string(),
        observed_summary: "the documented red path behaved exactly as written".to_string(),
        outcome: Outcome::Matched,
        id: "docs.first-hour.red-path".to_string(),
        docs_name: "getting-started".to_string(),
        stderr_excerpt: String::new(),
        declared_writes: Vec::new(),
        observed_writes: Vec::new(),
    });
    let evaluation = evaluate_release_experience_docs_execution_v1(&record(checks));
    if evaluation.result != State::NotProven {
        return Err(format!(
            "an honestly documented red path was denied agreement: {:?}",
            evaluation.gaps
        )
        .into());
    }
    Ok(())
}

